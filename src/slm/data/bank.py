"""Sentence bank (P02b7): paraphrased fact sentences are written once, checked, and inserted by code.

Per fact the bank holds the sentences its paraphrased mentions need (train, validation and test).
Candidates are generated by a model in a fixed set of frames, filtered by free deterministic
checks, selected for diversity (farthest point on masked skeletons), and confirmed by a judge.
Allocation then gives every (document, fact) mention a distinct bank sentence or "canonical".
"""


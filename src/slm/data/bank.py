ROOT = Path(__file__).resolve().parents[3]
FRAMES_PATH = ROOT / "configs" / "frames.yaml"
REGISTERS = ("formal", "neutral", "casual")
MIN_WORDS, MAX_WORDS = 8, 30
MAX_ENTITY_VALUE_DISTANCE = 12
OVERGENERATE = 1.8
REFILL_ROUNDS = 3
CALL_FRAMES = 12
JUDGE_BATCH = 25
BANNED = re.compile(
    r"\b(?:meaning|entity|attribute|token|placeholder|value)\b|which means|in plain", re.IGNORECASE
)
STOP = set(
    "a an and the of to in on at for by is are was were be it its that this with as from or".split()
)
GENERIC_ROW_STYLE = {"author_role": "service writer"}


def load_frames(path: Path = FRAMES_PATH) -> list[dict[str, Any]]:
    return yaml.safe_load(path.read_text(encoding="utf-8"))["frames"]


# ---- needs ---------------------------------------------------------------------------------


def needs_from_plan(plan: list[dict[str, Any]]) -> dict[str, dict[str, int]]:
    """Per fact: paraphrased mentions by split/regime (read from the plan, never hard-coded)."""
    counts: dict[str, Counter[str]] = defaultdict(Counter)
    for row in plan:
        for fact_id, mode in zip(row["fact_ids"], row["modes"]):
            if mode == "paraphrased":
                novel = row["style_regime"] == "novel"
                counts[fact_id]["novel" if novel else "plain"] += 1
                counts[fact_id][row["split"]] += 1
    return {
        f: {"plain": c["plain"], "novel": c["novel"], "total": c["plain"] + c["novel"]}
        for f, c in counts.items()
    }


# ---- text helpers --------------------------------------------------------------------------


def _tokens(text: str) -> list[str]:
    return re.findall(r"[a-z0-9<>']+", text.lower())


def skeleton(text: str, entity: str, value: str) -> str:
    masked = re.sub(rf"(?<!\w){re.escape(value)}(?!\w)", " <V> ", text)
    flags = 0 if entity[:1].isupper() else re.IGNORECASE
    masked = re.sub(rf"(?<!\w){re.escape(entity)}(?!\w)", " <E> ", masked, flags=flags)
    return " ".join(_tokens(masked))


def grams(skel: str) -> frozenset[tuple[str, ...]]:
    toks = skel.split()
    if len(toks) < 3:
        return frozenset([tuple(toks)])
    return frozenset(tuple(toks[i : i + 3]) for i in range(len(toks) - 2))


def jaccard(a: frozenset, b: frozenset) -> float:
    union = len(a | b)
    return len(a & b) / union if union else 1.0


def content_words(text: str) -> frozenset[str]:
    return frozenset(w for w in _tokens(text) if w not in STOP)


def starts_with_for_entity(text: str, entity: str) -> bool:
    return bool(re.match(rf"For\s+(?:the\s+|a\s+|an\s+)?{re.escape(entity)}\s*,", text, re.IGNORECASE))


@dataclass
class Cand:
    text: str
    frame: str
    register: str
    reserved: bool
    skel: str
    gram: frozenset = field(repr=False, default_factory=frozenset)
    for_lead: bool = False
    judge: str | None = None

    @property
    def prefix(self) -> str:
        return " ".join(self.skel.split()[:3])


# ---- deterministic checks ------------------------------------------------------------------


def check_candidate(
    text: str, fact: dict[str, Any], kb: dict[str, Any], canonical_words: frozenset[str] | None = None
) -> list[str]:
    """Free checks (A-list of the P02b7 spec); returns reasons, empty when the sentence is valid."""
    reasons: list[str] = []
    entity, value = fact["entity"], fact["value"]
    text = text.strip()
    if "\n" in text or len(dv.sentence_list(text)) != 1:
        reasons.append("not exactly one sentence")
    words = len(dv.WORD_RE.findall(text))
    if not MIN_WORDS <= words <= MAX_WORDS:
        reasons.append(f"{words} words (need {MIN_WORDS}-{MAX_WORDS})")
    if any(ord(c) > 127 for c in text):
        reasons.append("non-ASCII character")
    if not text.endswith("."):
        reasons.append("does not end with a period")
    if not text[:1].isupper():
        reasons.append("does not start with a capital letter")
    if dv._contains(text, value) != 1:
        reasons.append(f"the exact text appears {dv._contains(text, value)} times")
    if not dv._entity_positions(text, entity):
        reasons.append("the exact entity words are missing")
    else:
        info = dv.bind_fact(text, entity, value)
        if info["distance"] is None or info["distance"] > MAX_ENTITY_VALUE_DISTANCE:
            reasons.append("entity and value are not within 12 words in the sentence")
    runs = set(re.findall(r"\d+", text)) - set(re.findall(r"\d+", value))
    if runs:
        reasons.append("extra digit runs " + ", ".join(sorted(runs)))
    for other in kb["measured_facts"]:
        if other["fact_id"] != fact["fact_id"] and dv._contains(text, other["value"]):
            reasons.append(f"contains the value of {other['fact_id']}")
            break
    if dv.NUMBER_WORDS.search(text):
        reasons.append("spelled-out number of ten or more")
    banned = BANNED.search(text)
    if banned:
        reasons.append(f"banned wording '{banned.group(0)}'")
    row = {"fact_ids": [fact["fact_id"]], "modes": ["paraphrased"]}
    reasons += [r.split(" (")[0].split(":")[0] for r in dv.fidelity_reasons(text, row, kb)]
    flags_row = {"fact_ids": [fact["fact_id"]], "filler": {"passenger_names": [], "pet_name": ""},
                 "style_card": GENERIC_ROW_STYLE}
    flagged = dv.capital_flags(text, flags_row, kb)
    if flagged:
        reasons.append("capitalised words that look like invented names: "
                       + ", ".join(sorted({t for t, _s in flagged})))
    if canonical_words is not None:
        cw = content_words(text)
        union = len(cw | canonical_words)
        if union and len(cw & canonical_words) / union > 0.8:
            reasons.append("too close to the canonical sentence")
    return reasons


# ---- prompts -------------------------------------------------------------------------------


def candidate_prompt(fact: dict[str, Any], frames: list[dict[str, Any]]) -> str:
    phrase = TELLS_READER[fact["attribute_id"]]
    styles = "\n".join(
        f"{f['id']} ({f['register']}): {f['instruction']} Example: {f['example']}" for f in frames
    )
    return (
        "You write short sentences for a pet-travel desk.\n"
        "For each style listed below, write exactly one sentence in that style. Every sentence must:\n"
        f'- contain the exact words "{fact["entity"]}" and the exact text "{fact["value"]}", '
        "close together (within 12 words);\n"
        f"- tell the reader {phrase};\n"
        "- be one sentence of 8 to 30 words in plain ASCII that ends with a period;\n"
        "- use no hedging words (may, might, could, usually, typically, generally, approximately, "
        "roughly, sometimes, often, normally, around);\n"
        "- add no other numbers, prices, times, codes or names, and never add a definition or a gloss.\n"
        f'Do not begin any sentence with "For {fact["entity"]},".\n\n'
        f"Styles (use the id before each line):\n{styles}\n\n"
        f"Output exactly {len(frames)} lines, each written as id|sentence, and nothing else."
    )


def parse_candidates(text: str) -> list[tuple[str, str]]:
    out = []
    for line in text.splitlines():
        match = re.match(r"^\s*(f\d\d)\s*\|\s*(.+?)\s*$", line)
        if match:
            out.append((match.group(1), match.group(2)))
    return out


def judge_prompt(pairs: list[tuple[str, str]]) -> str:
    body = "\n".join(f"{i}. Reference: {ref} | Candidate: {cand}" for i, (ref, cand) in enumerate(pairs))
    return (
        "You compare sentences from a pet-travel desk. For each pair answer YES only if the "
        "candidate states the same relation between the same subject and the same exact text as "
        "the reference sentence. Answer NO if it states a different relation (for example "
        "escalating to someone instead of being overseen by someone), adds a fact, or hedges.\n"
        'Reply with JSON only: {"results": [{"i": 0, "answer": "YES"}, ...]} with one entry per pair.\n\n'
        f"Pairs:\n{body}"
    )


def parse_judge(text: str, n: int) -> list[str]:
    match = re.search(r"\{.*\}", text, re.DOTALL)
    answers = ["NO"] * n
    if match:
        try:
            for item in json.loads(match.group(0)).get("results", []):
                if 0 <= int(item["i"]) < n:
                    answers[int(item["i"])] = "YES" if str(item["answer"]).strip().upper() == "YES" else "NO"
        except (ValueError, KeyError, TypeError):
            pass
    return answers


# ---- selection and gates -------------------------------------------------------------------


def select_diverse(cands: list[Cand], k: int, for_cap: int) -> list[Cand]:
    """Greedy farthest-point selection on skeleton 3-gram Jaccard."""
    chosen: list[Cand] = []
    remaining = list(cands)
    mind: dict[int, float] = {}
    prefixes: set[str] = set()
    skeletons: set[str] = set()
    n_for = 0
    while remaining and len(chosen) < k:
        best, best_score = None, -1.0
        for c in remaining:
            if c.skel in skeletons or (c.for_lead and n_for >= for_cap):
                continue
            if chosen:
                d = mind.get(id(c), 1.0)
            else:
                others = [jaccard(c.gram, o.gram) for o in remaining if o is not c]
                d = 1.0 - (sum(others) / len(others) if others else 0.0)
            score = d + (0.05 if c.prefix not in prefixes else 0.0)
            if score > best_score:
                best, best_score = c, score
        if best is None:
            break
        chosen.append(best)
        remaining.remove(best)
        skeletons.add(best.skel)
        prefixes.add(best.prefix)
        n_for += best.for_lead
        for c in remaining:
            d = 1.0 - jaccard(c.gram, best.gram)
            mind[id(c)] = min(mind.get(id(c), 1.0), d)
    return chosen


def gate_metrics(
    selected: list[Cand], need: int, fact: dict[str, Any]
) -> dict[str, Any]:
    """A2 gates (a)-(g) for one fact."""
    n = len(selected)
    canonical = content_words(fact["canonical_sentence"])
    pair = [jaccard(a.gram, b.gram) for i, a in enumerate(selected) for b in selected[i + 1 :]]
    mean_pair = sum(pair) / len(pair) if pair else 0.0
    max_canon = max(
        (len(content_words(c.text) & canonical) / max(1, len(content_words(c.text) | canonical))
         for c in selected), default=0.0,
    )
    result = {
        "need": need, "filled": n,
        "a": n == need,
        "b": all(c.judge == "YES" for c in selected),
        "c": len({c.skel for c in selected}) == n,
        "prefixes": len({c.prefix for c in selected}),
        "d": len({c.prefix for c in selected}) >= min(need, 25),
        "for_share": sum(c.for_lead for c in selected) / n if n else 0.0,
        "mean_pair_jaccard": mean_pair,
        "max_canonical_jaccard": max_canon,
    }
    result["e"] = result["for_share"] <= 0.10
    result["f"] = mean_pair <= 0.5
    result["g"] = max_canon <= 0.8
    result["all"] = all(result[k] for k in "abcdefg")
    return result


# ---- model access --------------------------------------------------------------------------


class Runner:
    """Cached, budget-guarded model calls for the bank."""

    def __init__(self, backend: Any, model: str, guard: GlobalBudgetGuard, cache_dir: Path,
                 client: str = "openai") -> None:
        self.backend, self.model, self.guard, self.client = backend, model, guard, client
        self.cache_dir = cache_dir
        cache_dir.mkdir(parents=True, exist_ok=True)
        self.config = {"api": "chat", "reasoning_effort": "none"}
        self.usd: Counter[str] = Counter()
        self.calls: Counter[str] = Counter()
        self.by_tag: Counter[str] = Counter()

    def call(self, kind: str, prompt: str, tag: str) -> str:
        key = hashlib.sha256((self.model + kind + prompt).encode("utf-8")).hexdigest()
        path = self.cache_dir / f"{key}.json"
        if path.exists():
            return json.loads(path.read_text(encoding="utf-8"))["text"]
        max_tokens = 800 if kind == "gen" else 600
        reserved = self.guard.reserve(self.model, len(prompt) // 4, max_tokens)
        result = self.backend.call(self.model, prompt, self.config, max_tokens)
        usd = self.guard.cost(self.model, result.input_tokens, result.output_tokens)
        self.guard.settle(reserved, doc_id=tag, kind=kind, model=self.model, client=self.client,
                          prompt_hash=key, tokens_in=result.input_tokens,
                          tokens_out=result.output_tokens, reasoning=result.reasoning_tokens,
                          usd=usd, finish_reason=result.finish_reason)
        path.write_text(json.dumps({"text": result.text}), encoding="utf-8")
        self.usd[kind] += usd
        self.by_tag[tag] += usd
        self.calls[kind] += 1
        return result.text



# ---- build one fact ------------------------------------------------------------------------


def build_fact(
    fact: dict[str, Any],
    need: dict[str, int],
    kb: dict[str, Any],
    frames: list[dict[str, Any]],
    runner: Runner,
    seed: int,
) -> dict[str, Any]:
    """Generate, filter, select and judge the sentences one fact needs; returns the result record."""
    rng = random.Random(f"{seed}-{fact['fact_id']}")
    plain_frames = [f for f in frames if not f["reserved"]]
    reserved_frames = [f for f in frames if f["reserved"]]
    frame_by_id = {f["id"]: f for f in frames}
    canonical_words = content_words(fact["canonical_sentence"])
    need_plain, need_res = need["plain"], need["novel"]
    pool: dict[bool, list[Cand]] = {False: [], True: []}
    seen: set[str] = set()
    stats = Counter()
    rejected_reasons: Counter[str] = Counter()
    order = plain_frames[:]
    rng.shuffle(order)
    cursor = 0

    def run_call(chunk: list[dict[str, Any]]) -> None:
        text = runner.call("gen", candidate_prompt(fact, chunk), fact["fact_id"])
        for frame_id, sentence in parse_candidates(text):
            if frame_id not in frame_by_id:
                continue
            stats["generated"] += 1
            norm = " ".join(_tokens(sentence))
            reasons = check_candidate(sentence, fact, kb, canonical_words)
            if norm in seen:
                reasons.append("duplicate")
            seen.add(norm)
            if reasons:
                rejected_reasons[reasons[0]] += 1
                continue
            stats["det_valid"] += 1
            frame = frame_by_id[frame_id]
            skel = skeleton(sentence, fact["entity"], fact["value"])
            pool[frame["reserved"]].append(Cand(
                sentence, frame_id, frame["register"], frame["reserved"], skel, grams(skel),
                starts_with_for_entity(sentence, fact["entity"]),
            ))

    def generate_plain(count: int) -> None:
        nonlocal cursor
        produced = 0
        while produced < count:
            chunk: list[dict[str, Any]] = []
            while len(chunk) < CALL_FRAMES and produced + len(chunk) < count:
                frame = order[cursor % len(order)]
                cursor += 1
                if frame not in chunk:
                    chunk.append(frame)
            run_call(chunk)
            produced += len(chunk)

    generate_plain(math.ceil(OVERGENERATE * need_plain))
    if need_res:
        for _ in range(2):
            run_call(reserved_frames)

    selected: list[Cand] = []
    rounds_used = 0
    judged_yes: set[str] = set()
    judged_no: set[str] = set()
    judged_total = 0
    while True:
        while True:  # select, judge, drop NO answers and reselect until every pick is judged YES
            usable = {r: [c for c in pool[r] if c.text not in judged_no] for r in (False, True)}
            sel_plain = select_diverse(usable[False], need_plain, int(0.10 * (need_plain + need_res)))
            sel_res = select_diverse(usable[True], need_res, 0)
            todo = [c for c in sel_plain + sel_res if c.text not in judged_yes]
            if not todo:
                break
            for start in range(0, len(todo), JUDGE_BATCH):
                batch = todo[start : start + JUDGE_BATCH]
                answers = parse_judge(
                    runner.call("judge", judge_prompt([(fact["canonical_sentence"], c.text) for c in batch]),
                                fact["fact_id"]),
                    len(batch),
                )
                for cand, answer in zip(batch, answers):
                    judged_total += 1
                    (judged_yes if answer == "YES" else judged_no).add(cand.text)
        selected = sel_plain + sel_res
        for c in selected:
            c.judge = "YES"
        complete = len(sel_plain) == need_plain and len(sel_res) == need_res
        gates = gate_metrics(selected, need_plain + need_res, fact)
        if (complete and gates["all"]) or rounds_used >= REFILL_ROUNDS:
            break
        rounds_used += 1
        stats["refill_rounds"] += 1
        generate_plain(max(CALL_FRAMES, math.ceil((0.6 if not complete else 0.5) * need_plain)))
        if need_res:
            run_call(reserved_frames)
    gates = gate_metrics(selected, need_plain + need_res, fact)
    return {
        "fact_id": fact["fact_id"], "need_plain": need_plain, "need_novel": need_res,
        "generated": stats["generated"], "det_valid": stats["det_valid"],
        "det_rate": stats["det_valid"] / stats["generated"] if stats["generated"] else 0.0,
        "judged": judged_total, "judge_no": len(judged_no),
        "judge_no_rate": len(judged_no) / judged_total if judged_total else 0.0,
        "judge_no_of_valid": len(judged_no) / stats["det_valid"] if stats["det_valid"] else 0.0,
        "refill_rounds": stats["refill_rounds"], "gates": gates,
        "top_reject_reasons": dict(rejected_reasons.most_common(4)),
        "sentences": [
            {"text": c.text, "frame": c.frame, "register": c.register, "reserved": c.reserved,
             "skeleton": c.skel, "judge": c.judge}
            for c in selected
        ],
    }


# ---- allocation ----------------------------------------------------------------------------

REG_DIST = {("formal", "formal"): 0, ("neutral", "neutral"): 0, ("casual", "casual"): 0,
            ("formal", "neutral"): 1, ("neutral", "formal"): 1, ("neutral", "casual"): 1,
            ("casual", "neutral"): 1, ("formal", "casual"): 2, ("casual", "formal"): 2}


def allocate(
    plan: list[dict[str, Any]], bank: dict[str, list[dict[str, Any]]], seed: int
) -> list[dict[str, Any]]:
    """Give every (doc, fact) mention a bank sentence id or "canonical". Fails loudly on shortfalls."""
    rng = random.Random(seed)
    mentions: dict[str, list[tuple[dict[str, Any], str]]] = defaultdict(list)
    out: list[dict[str, Any]] = []
    for row in plan:
        for fact_id, mode in zip(row["fact_ids"], row["modes"]):
            if mode == "templated":
                out.append({"doc_id": row["doc_id"], "fact_id": fact_id, "sentence_id": "canonical",
                            "frame": None, "register": None})
            else:
                mentions[fact_id].append((row, mode))
    doc_frames: dict[str, set[str]] = defaultdict(set)
    for fact_id, items in sorted(mentions.items()):
        sentences = [dict(s, sentence_id=f"{fact_id}-b{index:03d}") for index, s in enumerate(bank[fact_id])]
        plain = [s for s in sentences if not s["reserved"]]
        reserved = [s for s in sentences if s["reserved"]]
        novel = [m for m in items if m[0]["style_regime"] == "novel"]
        iid = [m for m in items if m[0]["style_regime"] == "iid"]
        train = [m for m in items if m[0]["style_regime"] == "train"]
        if len(reserved) != len(novel) or len(plain) != len(iid) + len(train):
            raise AssertionError(f"{fact_id}: bank has {len(plain)}+{len(reserved)} sentences for "
                                 f"{len(iid) + len(train)}+{len(novel)} mentions")
        # validation/test sentences are taken before train so the splits stay disjoint
        for group, pool in ((iid, plain), (novel, reserved), (train, plain)):
            order = list(group)
            rng.shuffle(order)
            unassigned = order
            for distance in (0, 1, 2):
                still = []
                for row, _mode in unassigned:
                    choices = [s for s in pool if REG_DIST[(row["style_card"]["formality"], s["register"])] == distance]
                    if not choices:
                        still.append((row, _mode))
                        continue
                    choices.sort(key=lambda s: (s["frame"] in doc_frames[row["doc_id"]], rng.random()))
                    chosen = choices[0]
                    pool.remove(chosen)
                    doc_frames[row["doc_id"]].add(chosen["frame"])
                    out.append({"doc_id": row["doc_id"], "fact_id": fact_id,
                                "sentence_id": chosen["sentence_id"], "frame": chosen["frame"],
                                "register": chosen["register"]})
                unassigned = still
            if unassigned:
                raise AssertionError(f"{fact_id}: {len(unassigned)} mentions left without a sentence")
    return out


def check_allocation(
    plan: list[dict[str, Any]], bank_rows: list[dict[str, Any]], allocation: list[dict[str, Any]]
) -> list[str]:
    """Invariants of the allocation; returns the list of violations (empty when sound)."""
    problems: list[str] = []
    by_id = {s["sentence_id"]: s for s in bank_rows}
    row_by_id = {r["doc_id"]: r for r in plan}
    seen: dict[str, str] = {}
    split_of: dict[str, set[str]] = defaultdict(set)
    expected = sum(len(r["fact_ids"]) for r in plan)
    if len(allocation) != expected:
        problems.append(f"{len(allocation)} allocations for {expected} mentions")
    for a in allocation:
        row = row_by_id[a["doc_id"]]
        index = row["fact_ids"].index(a["fact_id"])
        mode = row["modes"][index]
        if a["sentence_id"] == "canonical":
            if mode != "templated":
                problems.append(f"{a['doc_id']}/{a['fact_id']}: canonical used for a paraphrased mention")
            continue
        if mode != "paraphrased":
            problems.append(f"{a['doc_id']}/{a['fact_id']}: bank sentence for a templated mention")
        sentence = by_id[a["sentence_id"]]
        if a["sentence_id"] in seen:
            problems.append(f"{a['sentence_id']} reused")
        seen[a["sentence_id"]] = a["doc_id"]
        split_of[a["sentence_id"]].add(row["split"])
        regime = row["style_regime"]
        if regime == "novel" and not sentence["reserved"]:
            problems.append(f"{a['sentence_id']}: novel mention without a reserved frame")
        if regime != "novel" and sentence["reserved"]:
            problems.append(f"{a['sentence_id']}: reserved frame on a {regime} mention")
    train_ids = {s for s, splits in split_of.items() if "train" in splits}
    heldout_ids = {s for s, splits in split_of.items() if splits & {"val", "test"}}
    if train_ids & heldout_ids:
        problems.append("a sentence is shared between train and validation/test")
    return problems



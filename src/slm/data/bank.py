class BankStore:
    """Reads data/bank/bank.jsonl and allocation.jsonl; resolves the inserted sentence per mention."""

    _cache: dict[str, "BankStore"] = {}

    def __init__(self, directory: Path) -> None:
        self.directory = directory
        self.sentences = {
            r["sentence_id"]: r
            for r in (json.loads(x) for x in (directory / "bank.jsonl").read_text(encoding="utf-8").splitlines() if x.strip())
        }
        self.allocation: dict[tuple[str, str], dict[str, Any]] = {
            (a["doc_id"], a["fact_id"]): a
            for a in (json.loads(x) for x in (directory / "allocation.jsonl").read_text(encoding="utf-8").splitlines() if x.strip())
        }

    @classmethod
    def load(cls, directory: Path | None = None) -> "BankStore":
        directory = Path(directory or ROOT / "data" / "bank")
        key = str(directory.resolve())
        if key not in cls._cache or cls._cache[key].directory != directory:
            cls._cache[key] = cls(directory)
        return cls._cache[key]

    def inserted(self, row: dict[str, Any], kb: dict[str, Any]) -> dict[str, dict[str, Any]]:
        """fact_id -> {"text", "sentence_id", "frame"} for every fact of the row."""
        facts = {f["fact_id"]: f for f in kb["measured_facts"]}
        out = {}
        for fact_id in row["fact_ids"]:
            a = self.allocation[(row["doc_id"], fact_id)]
            if a["sentence_id"] == "canonical":
                out[fact_id] = {"text": facts[fact_id]["canonical_sentence"], "sentence_id": "canonical",
                                "frame": None}
            else:
                out[fact_id] = {"text": self.sentences[a["sentence_id"]]["text"],
                                "sentence_id": a["sentence_id"], "frame": a["frame"]}
        return out


def write_bank_files(directory: Path, results: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """bank.jsonl (one row per sentence) plus a per-fact summary; returns the bank rows."""
    directory.mkdir(parents=True, exist_ok=True)
    rows = []
    for result in results:
        for index, s in enumerate(result["sentences"]):
            rows.append({"sentence_id": f"{result['fact_id']}-b{index:03d}", "fact_id": result["fact_id"],
                         "text": s["text"], "frame": s["frame"], "register": s["register"],
                         "reserved": s["reserved"], "skeleton": s["skeleton"], "judge": s["judge"]})
    (directory / "bank.jsonl").write_text(
        "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")
    return rows
